namespace Sling.Level.Elements.Tumbleweed
{
  public readonly struct TumbleweedSurface
  {
    public readonly float Left;
    public readonly float Right;
    public readonly float TopY;

    public TumbleweedSurface(float left, float right, float topY)
    {
      Left = left;
      Right = right;
      TopY = topY;
    }
  }
}
